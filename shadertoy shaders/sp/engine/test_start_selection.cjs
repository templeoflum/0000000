const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(__dirname + '/status.html', 'utf8');
// Compile every script as well as exercising the isolated patch controls.
for (const match of html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
const source = html.split('// START PATCH CONTROLS')[1].split('// END START PATCH CONTROLS')[0];
const elements = Object.fromEntries(['start-patch', 'use-as-start', 'patch-choice', 'recall-patch', 'action-feedback'].map(id => [id, {value: '', textContent: ''}]));
const sent = [];
const context = vm.createContext({document: {getElementById: id => elements[id]}, ws: {readyState: 1}, latestState: null, sentAt: 0, cmd: command => sent.push(command), Date});
vm.runInContext('// START PATCH CONTROLS' + source, context);
function state(start, patches = ['Start', 'Feedback checked']) {
  context.latestState = {surface: start ? {start_patch: start} : {}, patches, patch_recall_ready: true};
  context.paintPatchControls(context.latestState);
}
elements['patch-choice'].value = 'Feedback checked';
state();
assert.equal(elements['start-patch'].textContent, 'Start: Start');
context.recallStartPatch();
assert.equal(sent.pop().name, 'Start');
context.useSelectedAsStart();
assert.equal(sent.length, 1);
assert.equal(sent[0].cmd, 'surface_cfg');
assert.equal(sent.pop().value.start_patch, 'Feedback checked');
assert.equal(elements['start-patch'].textContent, 'Start: Start', 'wait for server acknowledgement');
state('Feedback checked');
assert.equal(elements['use-as-start'].disabled, true);
context.recallStartPatch();
assert.equal(sent.pop().name, 'Feedback checked');
state('Renamed patch');
assert.equal(elements['start-patch'].disabled, true);
assert.match(elements['start-patch'].textContent, /Renamed patch · missing/);
context.recallStartPatch();
assert.equal(sent.length, 0, 'missing target must not fall back to old Start');
context.ws.readyState = 3;
context.paintPatchControls(context.latestState, false);
assert.equal(elements['use-as-start'].disabled, true);
assert.equal(elements['recall-patch'].disabled, true);
context.useSelectedAsStart();
assert.equal(sent.length, 0);
context.ws.readyState = 1;
state('Feedback checked');
assert.equal(elements['start-patch'].disabled, false, 'server state restores target after reconnect');
context.latestState.patch_recall_ready = false;
context.paintPatchControls(context.latestState);
context.recallStartPatch();
assert.equal(sent.length, 0, 'busy operation must not recall');
elements['patch-choice'].value = 'Deleted choice';
context.useSelectedAsStart();
assert.equal(sent.length, 0, 'missing choice must not be saved');
state('<img src=x onerror=alert(1)>', ['<img src=x onerror=alert(1)>']);
assert.equal(elements['start-patch'].textContent, 'Start: <img src=x onerror=alert(1)>');
console.log('Start selection checks passed (default, configuration, acknowledgement, missing, reconnect, busy, text safety).');
